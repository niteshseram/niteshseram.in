'use client';

import { Check, Clipboard } from 'lucide';
import { MorphIcon } from 'morphicons/react';
import {
  useId,
  useRef,
  type ComponentProps,
  type HTMLAttributes,
  type ReactNode,
  type RefObject,
} from 'react';

import { IconButton } from '@/components/ui/icon-button';
import { ScrollArea } from '@/components/ui/scroll-area';
import { cn } from '@/lib/utils';
import { useCopyButton } from '@/utils/use-copy-button';

export interface CodeBlockProps extends ComponentProps<'figure'> {
  /**
   * Icon of code block
   *
   * When passed as a string, it assumes the value is the HTML of icon
   */
  icon?: ReactNode;

  /**
   * Allow to copy code with copy button
   *
   * @defaultValue true
   */
  allowCopy?: boolean;

  /**
   * Keep original background color generated by Shiki or Rehype Code
   *
   * @defaultValue false
   */
  keepBackground?: boolean;

  viewportProps?: HTMLAttributes<HTMLElement>;

  /**
   * show line numbers
   */
  'data-line-numbers'?: boolean;

  /**
   * @defaultValue 1
   */
  'data-line-numbers-start'?: number;

  Actions?: (props: { className?: string; children?: ReactNode }) => ReactNode;
}

const EMPTY_VIEWPORT_PROPS: HTMLAttributes<HTMLElement> = {};

function DefaultActions(props: { className?: string; children?: ReactNode }) {
  return <div {...props} className={cn('empty:hidden', props.className)} />;
}

export function Pre(props: ComponentProps<'pre'>) {
  return (
    <pre
      {...props}
      className={cn('min-w-full w-max *:flex *:flex-col', props.className)}
    >
      {props.children}
    </pre>
  );
}

export function CodeBlock({
  ref,
  title,
  allowCopy = true,
  keepBackground = false,
  icon,
  viewportProps = EMPTY_VIEWPORT_PROPS,
  children,
  Actions = DefaultActions,
  ...props
}: CodeBlockProps) {
  const captionId = useId();
  const areaRef = useRef<HTMLDivElement>(null);
  const {
    className: viewportClassNameProp,
    style: viewportStyleProp,
    ...viewportPropsRest
  } = viewportProps;

  return (
    <figure
      ref={ref}
      dir="ltr"
      {...props}
      tabIndex={-1}
      className={cn(
        'shiki relative overflow-hidden',
        'my-6',
        'rounded-md border',
        'text-sm',
        'bg-code border-border',
        keepBackground && 'bg-(--shiki-light-bg) dark:bg-(--shiki-dark-bg)',
        'not-prose',
        props.className,
      )}
    >
      {title ? (
        <div
          className={cn(
            'flex h-11 items-center gap-2',
            'px-4',
            'border-b',
            'text-sm',
            'bg-code-bar border-border text-muted-foreground',
          )}
        >
          {typeof icon === 'string' ? (
            <div
              className="[&_svg]:size-3.5"
              // oxlint-disable-next-line react/no-danger
              dangerouslySetInnerHTML={{
                __html: icon,
              }}
            />
          ) : (
            icon
          )}
          <figcaption className="flex-1 truncate" id={captionId}>
            {title}
          </figcaption>
          {Actions({
            className: '-me-2',
            children: allowCopy && <CopyButton containerRef={areaRef} />,
          })}
        </div>
      ) : (
        Actions({
          className: cn(
            'absolute top-2 right-2 z-2',
            'rounded-sm backdrop-blur',
            'text-muted-foreground',
          ),
          children: allowCopy && <CopyButton containerRef={areaRef} />,
        })
      )}
      <ScrollArea
        className="max-h-[600px]"
        orientation="both"
        viewportClassName={cn(
          'py-3.5',
          'text-sm leading-6',
          viewportClassNameProp,
        )}
        viewportProps={{
          ref: areaRef,
          role: 'region',
          ...(title
            ? { 'aria-labelledby': captionId }
            : { 'aria-label': 'Code example' }),
          ...viewportPropsRest,
          style: {
            // space for toolbar
            '--padding-right': !title ? 'calc(var(--spacing) * 8)' : undefined,
            counterSet: props['data-line-numbers']
              ? `line ${Number(props['data-line-numbers-start'] ?? 1) - 1}`
              : undefined,
            ...viewportStyleProp,
          } as object,
        }}
      >
        {children}
      </ScrollArea>
    </figure>
  );
}

function CopyButton({
  className,
  containerRef,
}: {
  className?: string;
  containerRef: RefObject<HTMLElement | null>;
}) {
  const [checked, onClick] = useCopyButton(() => {
    const pre = containerRef.current?.getElementsByTagName('pre').item(0);
    if (!pre) return;

    const clone = pre.cloneNode(true) as HTMLElement;
    clone.querySelectorAll('.nd-copy-ignore').forEach((node) => {
      node.replaceWith('\n');
    });

    void navigator.clipboard.writeText(clone.textContent ?? '');
  });

  return (
    <IconButton
      size="sm"
      label={checked ? 'Copied' : 'Copy code'}
      icon={
        <MorphIcon
          icon={checked ? Check : Clipboard}
          reducedMotion="user"
          size="100%"
          spring="snappy"
        />
      }
      tooltip={checked ? 'Copied!' : 'Copy code'}
      onClick={onClick}
      className={className}
    />
  );
}
